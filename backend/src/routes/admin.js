import { Router } from 'express';
import { requireAuth, requireAdmin } from '../middleware/auth.js';
import * as c from '../controllers/adminController.js';
const router = Router();
router.use(requireAuth, requireAdmin);
router.get('/resumen', c.resumenGet);
router.get('/productos', c.productosGet);
router.post('/productos', c.productoPost);
router.put('/productos/:id', c.productoPut);
router.delete('/productos/:id', c.productoDelete);
router.get('/pedidos', c.pedidosGet);
router.patch('/pedidos/:id', c.pedidoPatch);
router.get('/usuarios', c.usuariosGet);
router.get('/cupones', c.cuponesGet);
router.post('/cupones', c.cuponPost);
router.put('/cupones/:id', c.cuponPut);
router.delete('/cupones/:id', c.cuponDelete);
router.get('/ofertas', c.ofertasGet);
router.post('/ofertas', c.ofertaPost);
router.put('/ofertas/:id', c.ofertaPut);
router.delete('/ofertas/:id', c.ofertaDelete);
export default router;
